fn find_managed_index(arr: &[Value]) -> Option<usize> {
    // Primary identification: the explicit marker. Fallback: any entry whose
    // command invokes `altevra hook-handle` is ours regardless of marker —
    // legacy installs (adapter `connect` template, pre-marker versions) wrote
    // unmarked entries; without this fallback a re-install APPENDS a duplicate
    // and every hook event fires twice (double capture).
    arr.iter()
        .position(|v| {
            v.get(MANAGED_MARKER)
                .and_then(Value::as_bool)
                .unwrap_or(false)
        })
        .or_else(|| arr.iter().position(entry_invokes_altevra_hook_handle))
}

/// True when any nested hook command in this entry calls `altevra hook-handle`.
fn entry_invokes_altevra_hook_handle(entry: &Value) -> bool {
    entry
        .get("hooks")
        .and_then(Value::as_array)
        .map(|hooks| {
            hooks.iter().any(|h| {
                h.get("command")
                    .and_then(Value::as_str)
                    .is_some_and(|c| c.contains("altevra hook-handle"))
            })
        })
        .unwrap_or(false)
}

fn find_managed_index_yaml(arr: &[serde_yaml::Value]) -> Option<usize> {
    arr.iter().position(|v| {
        v.as_mapping()
            .and_then(|m| m.get(serde_yaml::Value::String("altevra_managed".into())))
            .and_then(serde_yaml::Value::as_bool)
            .unwrap_or(false)
    })
}

/// Two entries are "equal" if they match after stripping the marker key. This
/// is how we detect a managed entry that hasn't drifted (idempotent re-run).
fn entries_equal_ignoring_marker(a: &Value, b: &Value) -> bool {
    let mut a = a.clone();
    let mut b = b.clone();
    if let Some(o) = a.as_object_mut() {
        o.remove(MANAGED_MARKER);
    }
    if let Some(o) = b.as_object_mut() {
        o.remove(MANAGED_MARKER);
    }
    a == b
}

fn yaml_entries_equal_ignoring_marker(a: &serde_yaml::Value, b: &serde_yaml::Value) -> bool {
    let strip = |v: &serde_yaml::Value| -> serde_yaml::Value {
        let mut c = v.clone();
        if let Some(m) = c.as_mapping_mut() {
            m.remove(serde_yaml::Value::String("altevra_managed".into()));
        }
        c
    };
    strip(a) == strip(b)
}

