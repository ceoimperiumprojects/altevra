    async fn install_hooks_smart_scope_decides_per_project() {
        let _guard = cwd_lock();
        let tmp = TempDir::new().unwrap();
        let home = tmp.path();
        let projects = home.join("projekti");
        fs::create_dir_all(&projects).unwrap();

        // Repo A: score >= 3 (CLAUDE.md + existing non-altevra hooks + yaml entry P0).
        let a = projects.join("ai-tooling/high-score");
        fs::create_dir_all(a.join(".git")).unwrap();
        fs::write(a.join("CLAUDE.md"), "x").unwrap();
        fs::create_dir_all(a.join(".claude")).unwrap();
        fs::write(
            a.join(".claude/settings.json"),
            r#"{"hooks":{"SessionStart":[{"matcher":"","hooks":[{"type":"command","command":"echo hi"}]}]}}"#,
        )
        .unwrap();

        // Repo B: bare (score 0).
        let b = projects.join("ai-tooling/bare");
        fs::create_dir_all(b.join(".git")).unwrap();

        // Repo C: has .altevra-skip marker.
        let c = projects.join("ai-tooling/skip-me");
        fs::create_dir_all(c.join(".git")).unwrap();
        fs::write(c.join(".altevra-skip"), "").unwrap();

        // Seed minimal projects.yaml referencing repo A as P0 with default_agent.
        let yaml_path = home.join(".imperium/identity/projects.yaml");
        fs::create_dir_all(yaml_path.parent().unwrap()).unwrap();
        let yaml = format!(
            "version: 1\nprojects:\n  - id: high-score\n    path: \"{}\"\n    default_agent: claude\n    priority: P0\n",
            a.display()
        );
        fs::write(&yaml_path, yaml).unwrap();

        let decisions = smart_scope_apply(home, &projects).unwrap();
        let a_decision = decisions
            .iter()
            .find(|d| d.path == a)
            .expect("repo A missing from decisions");
        assert!(a_decision.score >= 3, "repo A score < 3: {a_decision:?}");
        assert!(
            a_decision.action.contains("WROTE") || a_decision.action.contains("SKIP-ALREADY-MANAGED"),
            "expected write for high-score repo, got {}",
            a_decision.action
        );
        // Bare repo gets skipped or low-score.
        if let Some(b_decision) = decisions.iter().find(|d| d.path == b) {
            assert!(b_decision.score < 3);
            assert_eq!(b_decision.action, "SKIP-LOW-SCORE");
        }
        // Skip-marker repo never appears in decisions.
        assert!(
            decisions.iter().all(|d| d.path != c),
            "repo with .altevra-skip should be omitted"
        );

        // Decisions log exists and references at least one repo.
        let log = fs::read_to_string(home.join(".altevra/install-hooks-decisions.log")).unwrap();
        assert!(log.contains("high-score"));
        assert!(log.contains("skip-me\tSKIP"));
    }

