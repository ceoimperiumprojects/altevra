//! `altevra install-hooks` — the load-bearing one-shot that wires Altevra into
//! every AI tool Pavle uses (Claude Code, Codex, Cursor CLI, Hermes).
//!
//! ## Why this command exists
//!
//! Today Pavle has to hand-edit four different config files (each with its own
//! schema) to make Altevra see his sessions. This command does it once, safely,
//! additively (never deletes existing `imperium-emit` lines), with a backup
//! before every write and idempotent re-runs.
//!
//! ## Safety contract (CRITICAL)
//!
//! 1. **Backup before every write** — `cp <config> <config>.altevra-backup-<unix_ts>`,
//!    unconditionally, BEFORE parsing or modifying anything.
//! 2. **Additive only** — never delete existing entries. We append Altevra entries
//!    alongside whatever else is there (imperium-emit, herdr, gsd hooks, ...).
//! 3. **Self-skip (SI-6 — two layers)** —
//!    - **Global gate** — `run()` refuses entirely (with a `bail!`) when the
//!      current working directory is inside the Altevra workspace. This stops
//!      Pavle from accidentally wiring `$HOME/.claude/settings.json` (which
//!      lives OUTSIDE the repo) while sitting in the repo: those global hooks
//!      would fire during Altevra's own dev sessions and create a feedback
//!      loop. Override with `ALTEVRA_BYPASS_SELF_SKIP=1` only if you really
//!      mean it.
//!    - **Per-target check** — `is_altevra_repo_target()` additionally refuses
//!      when a *specific* target path is itself inside the Altevra workspace
//!      (e.g. smart-scope landing on the repo's own `.claude/settings.json`).
//!
//!    Both layers detect Altevra by *parsing* `Cargo.toml` — `[package].name`
//!    equals `altevra` or starts with `altevra-`, OR the file is a workspace
//!    root listing `altevra-*` members. Substring matches on raw text are
//!    forbidden because a downstream Cargo.toml may legitimately list
//!    `altevra = "x.y"` as a dependency.
//! 4. **Idempotent** — re-running with no changes does nothing; entries are
//!    identified by the `_altevra_managed: true` marker.
//! 5. **Drift = require --force** — if a managed entry exists with content that
//!    differs from what we'd write now, abort unless `--force` is passed.
//! 6. **Post-write validation** — re-parse the written file; on parse failure
//!    restore from backup.
//!
//! ## Schemas (one per tool)
//!
//! | Tool        | Path                    | Format | Schema                                                          |
//! |-------------|-------------------------|--------|-----------------------------------------------------------------|
//! | claude-code | `~/.claude/settings.json` | JSON   | `{hooks: {EventName: [{matcher, hooks: [{type, command, ...}]}]}}` |
//! | codex       | `~/.codex/hooks.json`     | JSON   | identical to claude-code                                        |
//! | cursor      | `~/.cursor/hooks.json`    | JSON   | v1: `{hooks: {eventName: [{command}]}}`, no matcher, camelCase  |
//! | hermes      | `~/.hermes/config.yaml`   | YAML   | `hooks: {event_name: [{command, timeout?}]}`, snake_case        |
//!
//! For Hermes we ALSO copy `altevra-ingest.sh` into `~/.hermes/hooks/` and chmod
//! 0755 — the bridge script generated by `altevra-adapters::hermes_ingest_sh`.
//!
//! ## Smart auto-scope (Pavle: "Altevra decides, not me")
//!
//! After global wire, we scan `~/.imperium/identity/projects.yaml` and
//! `~/projekti/` for git repos and score each. Repos with score >= 3 also get a
//! per-project `.claude/settings.json`. Decisions are logged to
//! `~/.altevra/install-hooks-decisions.log` for transparency.

use anyhow::{bail, Context as _, Result};
use clap::Args;
use serde_json::{json, Map, Value};
use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

/// Marker key embedded in every Altevra-written hook entry. Used for
/// idempotency (skip if present) and drift detection (compare commands).
pub const MANAGED_MARKER: &str = "_altevra_managed";

/// Tools we support. The CLI's `--tool` flag accepts these strings (or `all`).
const SUPPORTED_TOOLS: &[&str] = &["claude-code", "codex", "cursor", "hermes"];

/// Set this to `1` to override the SI-6 global self-skip gate (run from inside
/// the Altevra repo). Intended only for maintainers explicitly re-wiring after
/// a clean state — normal users should never need it.
const SELF_SKIP_BYPASS_ENV: &str = "ALTEVRA_BYPASS_SELF_SKIP";

#[derive(Args, Clone, Debug)]
pub struct InstallHooksArgs {
    /// Which tool to wire. Defaults to wiring all four.
    #[arg(long)]
    pub tool: Option<String>,

    /// Overwrite drifted Altevra-managed entries (entries whose command we'd
    /// change). Without `--force`, drift causes an abort with a clear message.
    #[arg(long)]
    pub force: bool,

    /// Print planned changes without touching any file.
    #[arg(long)]
    pub dry_run: bool,

    /// Override $HOME (used in tests so we never touch Pavle's real configs).
    #[arg(long, hide = true)]
    pub home: Option<PathBuf>,

    /// Override the smart-scope walk root (defaults to `$HOME/projekti`).
    /// Tests point this at a temp dir; real runs leave it None.
    #[arg(long, hide = true)]
    pub projects_root: Option<PathBuf>,

    /// Bypass the SI-6 global self-skip gate (run from inside the altevra
    /// repo). Equivalent to setting `ALTEVRA_BYPASS_SELF_SKIP=1`. Hidden flag
    /// intended for in-process tests that already operate against a TempDir
    /// HOME, so process-global env mutation isn't needed.
    #[arg(long, hide = true)]
    pub bypass_self_skip: bool,
}

/// Outcome of patching one tool's global config, returned for reporting.
#[derive(Debug, Clone, Default)]
pub struct PatchOutcome {
    pub tool: String,
    pub config_path: PathBuf,
    pub backup_path: Option<PathBuf>,
    pub added_events: Vec<String>,
    pub skipped_events: Vec<String>,
    pub drifted_events: Vec<String>,
    pub self_skipped: bool,
    pub dry_run: bool,
}

pub async fn run(args: InstallHooksArgs) -> Result<()> {
    let home = resolve_home(&args)?;
    let tools = resolve_tool_set(args.tool.as_deref())?;

    // SI-6 global self-skip gate: refuse the entire install when cwd is inside
    // the Altevra workspace. The per-target check below catches the case where
    // a *specific* target sits inside the repo, but the global config paths
    // ($HOME/.claude/settings.json etc.) live OUTSIDE the repo — so without
    // this gate, running `altevra install-hooks` from `~/projekti/.../altevra`
    // would happily patch global configs and create a feedback loop in
    // Altevra's own dev sessions.
    let bypass_self_skip = args.bypass_self_skip
        || std::env::var(SELF_SKIP_BYPASS_ENV).ok().as_deref() == Some("1");
    if let Some(repo_root) = detect_altevra_workspace_from_cwd() {
        let cwd = std::env::current_dir().ok();
        log_self_skip_decision(&home, repo_root.as_path(), cwd.as_deref(), bypass_self_skip);
        if !bypass_self_skip {
            bail!(
                "altevra install-hooks refuses to run from inside the altevra repo itself \
                 (SI-6 self-write exclusion). Detected workspace at {}. Run it from another \
                 directory or set {SELF_SKIP_BYPASS_ENV}=1 to override.",
                repo_root.display()
            );
        }
    }

    println!("altevra install-hooks");
    println!("  home: {}", home.display());
    println!("  tools: {}", tools.join(", "));
    println!("  mode: {}", if args.dry_run { "dry-run" } else { "apply" });
    println!();

    let mut outcomes = Vec::new();
    for tool in &tools {
        let outcome = match tool.as_str() {
            "claude-code" => patch_claude_code(&home, args.force, args.dry_run)?,
            "codex" => patch_codex(&home, args.force, args.dry_run)?,
            "cursor" => patch_cursor(&home, args.force, args.dry_run)?,
            "hermes" => patch_hermes(&home, args.force, args.dry_run)?,
            other => bail!("unknown tool '{other}'"),
        };
        print_outcome(&outcome);
        outcomes.push(outcome);
    }

    // Smart scope: only when wiring all (no --tool filter); never during dry-run.
    if args.tool.is_none() && !args.dry_run {
        let scope_root = args
            .projects_root
            .clone()
            .unwrap_or_else(|| home.join("projekti"));
        if scope_root.exists() {
            let decisions = smart_scope_apply(&home, &scope_root)?;
            println!("\nsmart-scope decisions: {} repos", decisions.len());
            for d in &decisions {
                println!("  - {} score={} action={}", d.path.display(), d.score, d.action);
            }
        }
    }

    Ok(())
}

fn print_outcome(o: &PatchOutcome) {
    println!("[{}]", o.tool);
    println!("  config: {}", o.config_path.display());
    if o.self_skipped {
        println!("  SELF-SKIP: detected altevra repo as the target — refusing to wire.");
        return;
    }
    if let Some(b) = &o.backup_path {
        println!("  backup: {}", b.display());
    }
    if !o.added_events.is_empty() {
        println!("  added: {}", o.added_events.join(", "));
    }
    if !o.skipped_events.is_empty() {
        println!("  already-managed (skipped): {}", o.skipped_events.join(", "));
    }
    if !o.drifted_events.is_empty() {
        println!(
            "  DRIFT (need --force to overwrite): {}",
            o.drifted_events.join(", ")
        );
    }
    if o.dry_run {
        println!("  (dry-run — no file written)");
    }
}

// ───────────────────────────────────────────────────────────────────────────
// Tool selection / home resolution
// ───────────────────────────────────────────────────────────────────────────

fn resolve_home(args: &InstallHooksArgs) -> Result<PathBuf> {
    if let Some(h) = &args.home {
        return Ok(h.clone());
    }
    let h = std::env::var("HOME").context("HOME not set")?;
    Ok(PathBuf::from(h))
}

fn resolve_tool_set(filter: Option<&str>) -> Result<Vec<String>> {
    match filter {
        None | Some("all") => Ok(SUPPORTED_TOOLS.iter().map(|s| s.to_string()).collect()),
        Some(one) if SUPPORTED_TOOLS.contains(&one) => Ok(vec![one.to_string()]),
        Some(other) => bail!(
            "unknown --tool '{other}'; supported: {}",
            SUPPORTED_TOOLS.join(", ")
        ),
    }
}

// ───────────────────────────────────────────────────────────────────────────
// Backup helper (unconditional, BEFORE any write)
// ───────────────────────────────────────────────────────────────────────────

/// Copy `path` to `path.altevra-backup-<unix_ts>` so any future write is
/// recoverable. If the source doesn't exist (first-time install), we return
/// `None` (nothing to back up).
fn backup_file(path: &Path) -> Result<Option<PathBuf>> {
    if !path.exists() {
        return Ok(None);
    }
    let ts = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let backup = path.with_extension(format!(
        "{}.altevra-backup-{}",
        path.extension().and_then(|s| s.to_str()).unwrap_or(""),
        ts
    ));
    fs::copy(path, &backup).with_context(|| {
        format!("failed to back up {} → {}", path.display(), backup.display())
    })?;
    Ok(Some(backup))
}

/// Restore `path` from `backup` on any post-write validation failure.
fn restore_from_backup(path: &Path, backup: &Path) -> Result<()> {
    fs::copy(backup, path)
        .with_context(|| format!("failed to restore {} from {}", path.display(), backup.display()))?;
    Ok(())
}

// ───────────────────────────────────────────────────────────────────────────
// Event matrices
// ───────────────────────────────────────────────────────────────────────────

/// Claude Code / Codex event matrix: (EventName, altevra-event-arg).
fn claude_event_matrix() -> &'static [(&'static str, &'static str)] {
    &[
        ("SessionStart", "session_start"),
        ("UserPromptSubmit", "user_prompt_submit"),
        ("PreToolUse", "pre_tool_use"),
        ("PostToolUse", "post_tool_use"),
        // Claude Code fires `Stop` after EVERY assistant turn, NOT only at
        // session termination. Mapping it to `session_end` (the old bug) made
        // `clear_current_session` delete the pointer after the first response,
        // so every subsequent turn silently dropped. `stop` is a SOFT
        // CHECKPOINT that accrues stats without clearing the pointer.
        ("Stop", "stop"),
    ]
}

/// Cursor v1 schema: lowerCamelCase event names, no matcher.
fn cursor_event_matrix() -> &'static [(&'static str, &'static str)] {
    &[
        ("sessionStart", "session_start"),
        ("postToolUse", "post_tool_use"),
        // Soft checkpoint (see claude_event_matrix) — not a session_end.
        ("stop", "stop"),
    ]
}

/// Hermes snake_case event names. The COMMAND for hermes is ALWAYS the bridge
/// script `~/.hermes/hooks/altevra-ingest.sh` — Hermes' own shell_hooks.py reads
/// `HOOK_EVENT_NAME` and the bridge maps to the correct Altevra event.
fn hermes_event_list() -> &'static [&'static str] {
    &[
        "pre_tool_call",
        "post_tool_call",
        "post_llm_call",
        "session_start",
        "session_end",
    ]
}

// ───────────────────────────────────────────────────────────────────────────
// Claude Code / Codex (shared JSON schema)
// ───────────────────────────────────────────────────────────────────────────

fn patch_claude_code(home: &Path, force: bool, dry_run: bool) -> Result<PatchOutcome> {
    let config = home.join(".claude/settings.json");
    patch_claude_style(config, "claude-code", force, dry_run)
}

fn patch_codex(home: &Path, force: bool, dry_run: bool) -> Result<PatchOutcome> {
    let config = home.join(".codex/hooks.json");
    patch_claude_style(config, "codex", force, dry_run)
}

fn patch_claude_style(
    config: PathBuf,
    tool: &str,
    force: bool,
    dry_run: bool,
) -> Result<PatchOutcome> {
    let mut outcome = PatchOutcome {
        tool: tool.to_string(),
        config_path: config.clone(),
        dry_run,
        ..Default::default()
    };

    if is_altevra_repo_target(&config) {
        outcome.self_skipped = true;
        return Ok(outcome);
    }

    // Backup BEFORE parsing — even a read could fail, but a corrupted file
    // shouldn't lose Pavle's data.
    if !dry_run {
        outcome.backup_path = backup_file(&config)?;
    }

    // Read existing config (or start from empty if first-time install).
    let mut root: Value = if config.exists() {
        let text = fs::read_to_string(&config)
            .with_context(|| format!("read {}", config.display()))?;
        serde_json::from_str(&text)
            .with_context(|| format!("parse {} as JSON", config.display()))?
    } else {
        Value::Object(Map::new())
    };

    let hooks = root
        .as_object_mut()
        .context("root is not a JSON object")?
        .entry("hooks")
        .or_insert_with(|| Value::Object(Map::new()))
        .as_object_mut()
        .context("hooks is not an object")?;

    for (event, altevra_arg) in claude_event_matrix() {
        let desired = claude_style_altevra_entry(tool, altevra_arg);
        let arr = hooks
            .entry((*event).to_string())
            .or_insert_with(|| Value::Array(Vec::new()))
            .as_array_mut()
            .with_context(|| format!("{event} entry is not an array"))?;
        match find_managed_index(arr) {
            Some(idx) => {
                if entries_equal_ignoring_marker(&arr[idx], &desired) {
                    outcome.skipped_events.push((*event).to_string());
                } else if force {
                    arr[idx] = desired;
                    outcome.added_events.push(format!("{event} (forced)"));
                } else {
                    outcome.drifted_events.push((*event).to_string());
                }
            }
            None => {
                arr.push(desired);
                outcome.added_events.push((*event).to_string());
            }
        }
        // Dedup: exactly ONE altevra entry per event. Legacy installs +
        // marker-blind re-installs leave variants behind, and each extra
        // double-fires the hook (double capture). Keep the canonical entry,
        // drop every other altevra-invoking entry; non-altevra entries
        // (imperium-emit etc.) are never touched — the additive contract
        // applies to foreign hooks, not our own duplicates.
        if !outcome.drifted_events.contains(&(*event).to_string()) {
            if let Some(keep) = find_managed_index(arr) {
                let mut i = arr.len();
                while i > 0 {
                    i -= 1;
                    if i != keep && entry_invokes_altevra_hook_handle(&arr[i]) {
                        arr.remove(i);
                        outcome
                            .added_events
                            .push(format!("{event} (deduped extra entry)"));
                    }
                }
            }
        }
    }

    if !outcome.drifted_events.is_empty() && !force {
        bail!(
            "[{}] drift detected on managed entries: {} — re-run with --force to overwrite",
            tool,
            outcome.drifted_events.join(", ")
        );
    }

    if dry_run {
        return Ok(outcome);
    }

    // Only write if we actually changed something.
    let nothing_changed = outcome.added_events.is_empty();
    if nothing_changed {
        return Ok(outcome);
    }
    write_json_pretty(&config, &root)?;
    // Post-write validation: re-parse; on failure restore.
    if let Err(e) = serde_json::from_str::<Value>(
        &fs::read_to_string(&config).unwrap_or_default(),
    ) {
        if let Some(b) = &outcome.backup_path {
            restore_from_backup(&config, b)?;
        }
        bail!("[{tool}] post-write JSON validation failed: {e} — restored from backup");
    }
    Ok(outcome)
}

/// Build the Claude/Codex hook entry we want to write for `event`. The entry
/// carries `_altevra_managed: true` so future runs recognise it.
///
/// P0 hardening (PLAN-ALIVE.md): bake the absolute `--db` path resolved on
/// the installing machine so a hook can never resolve a CWD-relative shadow
/// DB. Project/working_dir are derived inside hook-handle from
/// `$CLAUDE_PROJECT_DIR`/cwd — no `$ALTEVRA_PROJECT`.
fn claude_style_altevra_entry(_tool: &str, altevra_arg: &str) -> Value {
    let db = altevra_core::paths::default_db_path().display().to_string();
    json!({
        "matcher": "*",
        "_altevra_managed": true,
        "hooks": [{
            "type": "command",
            "command": format!("altevra hook-handle {altevra_arg} --tool {_tool} --db {db}"),
            "timeout": 5
        }]
    })
}

// ───────────────────────────────────────────────────────────────────────────
// Cursor (JSON v1 — no matcher, camelCase)
// ───────────────────────────────────────────────────────────────────────────

fn patch_cursor(home: &Path, force: bool, dry_run: bool) -> Result<PatchOutcome> {
    let config = home.join(".cursor/hooks.json");
    let mut outcome = PatchOutcome {
        tool: "cursor".to_string(),
        config_path: config.clone(),
        dry_run,
        ..Default::default()
    };

    if is_altevra_repo_target(&config) {
        outcome.self_skipped = true;
        return Ok(outcome);
    }

    if !dry_run {
        outcome.backup_path = backup_file(&config)?;
    }

    let mut root: Value = if config.exists() {
        let text = fs::read_to_string(&config)?;
        serde_json::from_str(&text)
            .with_context(|| format!("parse {} as JSON", config.display()))?
    } else {
        json!({"version": 1, "hooks": {}})
    };

    if root.get("version").is_none() {
        root.as_object_mut().unwrap().insert("version".into(), json!(1));
    }
    let hooks = root
        .as_object_mut()
        .context("root is not an object")?
        .entry("hooks")
        .or_insert_with(|| Value::Object(Map::new()))
        .as_object_mut()
        .context("hooks is not an object")?;

    for (event, altevra_arg) in cursor_event_matrix() {
        let desired = json!({
            "_altevra_managed": true,
            "command": format!("altevra hook-handle {altevra_arg} --tool cursor")
        });
        let arr = hooks
            .entry((*event).to_string())
            .or_insert_with(|| Value::Array(Vec::new()))
            .as_array_mut()
            .with_context(|| format!("cursor {event} entry is not an array"))?;
        match find_managed_index(arr) {
            Some(idx) => {
                if entries_equal_ignoring_marker(&arr[idx], &desired) {
                    outcome.skipped_events.push((*event).to_string());
                } else if force {
                    arr[idx] = desired;
                    outcome.added_events.push(format!("{event} (forced)"));
                } else {
                    outcome.drifted_events.push((*event).to_string());
                }
            }
            None => {
                arr.push(desired);
                outcome.added_events.push((*event).to_string());
            }
        }
    }

    if !outcome.drifted_events.is_empty() && !force {
        bail!(
            "[cursor] drift detected on managed entries: {} — re-run with --force",
            outcome.drifted_events.join(", ")
        );
    }

    if dry_run {
        return Ok(outcome);
    }
    if outcome.added_events.is_empty() {
        return Ok(outcome);
    }
    write_json_pretty(&config, &root)?;
    if let Err(e) = serde_json::from_str::<Value>(
        &fs::read_to_string(&config).unwrap_or_default(),
    ) {
        if let Some(b) = &outcome.backup_path {
            restore_from_backup(&config, b)?;
        }
        bail!("[cursor] post-write JSON validation failed: {e} — restored from backup");
    }
    Ok(outcome)
}

// ───────────────────────────────────────────────────────────────────────────
// Hermes (YAML — config + bridge script + chmod 0755)
// ───────────────────────────────────────────────────────────────────────────

fn patch_hermes(home: &Path, force: bool, dry_run: bool) -> Result<PatchOutcome> {
    let config = home.join(".hermes/config.yaml");
    let bridge_path = home.join(".hermes/hooks/altevra-ingest.sh");
    let mut outcome = PatchOutcome {
        tool: "hermes".to_string(),
        config_path: config.clone(),
        dry_run,
        ..Default::default()
    };

    if is_altevra_repo_target(&config) {
        outcome.self_skipped = true;
        return Ok(outcome);
    }

    if !dry_run {
        outcome.backup_path = backup_file(&config)?;
    }

    // 1) Install the bridge script (idempotent — overwrite is fine, content is
    //    fully managed by altevra-adapters::hermes_ingest_sh).
    if !dry_run {
        install_hermes_bridge(&bridge_path)?;
    }

    // 2) Patch the YAML hooks section.
    let mut root: serde_yaml::Value = if config.exists() {
        let text = fs::read_to_string(&config)?;
        serde_yaml::from_str(&text)
            .with_context(|| format!("parse {} as YAML", config.display()))?
    } else {
        serde_yaml::Value::Mapping(Default::default())
    };

    let root_map = root
        .as_mapping_mut()
        .context("hermes config root is not a mapping")?;

    let hooks_key = serde_yaml::Value::String("hooks".into());
    if !root_map.contains_key(&hooks_key) {
        root_map.insert(hooks_key.clone(), serde_yaml::Value::Mapping(Default::default()));
    }
    let hooks = root_map
        .get_mut(&hooks_key)
        .unwrap()
        .as_mapping_mut()
        .context("hermes hooks is not a mapping")?;

    let bridge_cmd = bridge_path.to_string_lossy().into_owned();
    let desired_entry = hermes_managed_entry(&bridge_cmd);

    for event in hermes_event_list() {
        let key = serde_yaml::Value::String((*event).into());
        if !hooks.contains_key(&key) {
            hooks.insert(key.clone(), serde_yaml::Value::Sequence(Vec::new()));
        }
        let arr = hooks
            .get_mut(&key)
            .unwrap()
            .as_sequence_mut()
            .with_context(|| format!("hermes hooks.{event} is not a sequence"))?;
        match find_managed_index_yaml(arr) {
            Some(idx) => {
                if yaml_entries_equal_ignoring_marker(&arr[idx], &desired_entry) {
                    outcome.skipped_events.push((*event).to_string());
                } else if force {
                    arr[idx] = desired_entry.clone();
                    outcome.added_events.push(format!("{event} (forced)"));
                } else {
                    outcome.drifted_events.push((*event).to_string());
                }
            }
            None => {
                arr.push(desired_entry.clone());
                outcome.added_events.push((*event).to_string());
            }
        }
    }

    if !outcome.drifted_events.is_empty() && !force {
        bail!(
            "[hermes] drift detected on managed entries: {} — re-run with --force",
            outcome.drifted_events.join(", ")
        );
    }

    if dry_run {
        return Ok(outcome);
    }
    if outcome.added_events.is_empty() {
        return Ok(outcome);
    }
    write_yaml(&config, &root)?;
    if let Err(e) = serde_yaml::from_str::<serde_yaml::Value>(
        &fs::read_to_string(&config).unwrap_or_default(),
    ) {
        if let Some(b) = &outcome.backup_path {
            restore_from_backup(&config, b)?;
        }
        bail!("[hermes] post-write YAML validation failed: {e} — restored from backup");
    }
    Ok(outcome)
}

/// Write the Hermes → Altevra bridge script and chmod 0755. Content is the
/// canonical text from `altevra-adapters::hermes_ingest_sh` so the script and
/// the in-process event mapping always agree.
fn install_hermes_bridge(path: &Path) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let body = altevra_adapters::hermes_ingest_sh::altevra_ingest_sh_content();
    fs::write(path, body)
        .with_context(|| format!("write bridge {}", path.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = fs::metadata(path)?.permissions();
        perms.set_mode(0o755);
        fs::set_permissions(path, perms)?;
    }
    Ok(())
}

fn hermes_managed_entry(bridge_cmd: &str) -> serde_yaml::Value {
    let mut m = serde_yaml::Mapping::new();
    m.insert(
        serde_yaml::Value::String("command".into()),
        serde_yaml::Value::String(bridge_cmd.into()),
    );
    m.insert(
        serde_yaml::Value::String("timeout".into()),
        serde_yaml::Value::Number(serde_yaml::Number::from(5_i64)),
    );
    // Hermes shell_hooks.py uses raw.get("command") / raw.get("timeout") — extra
    // keys are silently ignored, so this marker is safe and survives YAML
    // round-trips (unlike `# altevra-managed` comments which serde_yaml strips).
    m.insert(
        serde_yaml::Value::String("altevra_managed".into()),
        serde_yaml::Value::Bool(true),
    );
    serde_yaml::Value::Mapping(m)
}

