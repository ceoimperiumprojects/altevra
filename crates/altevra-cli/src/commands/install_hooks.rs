/// True if the target config path lives inside the Altevra workspace. Used by
/// the per-target self-skip (e.g. when smart-scope would patch the repo's own
/// `.claude/settings.json`). The global-gate in `run()` handles the case where
/// the *cwd* is inside the repo but the *target* is outside it.
fn is_altevra_repo_target(target: &Path) -> bool {
    // Walk up from the target itself, since the target is the path we'd write.
    if let Some(root) = find_altevra_workspace_from(target) {
        if target.starts_with(&root) {
            return true;
        }
    }
    // Belt-and-braces: also catch the case where cwd is in the altevra repo
    // and the target sits within it (preserves prior behaviour for the
    // existing `install_hooks_self_skip_altevra_repo` test where the target
    // is inside cwd).
    if let Ok(cwd) = std::env::current_dir() {
        if let Some(root) = find_altevra_workspace_from(&cwd) {
            if target.starts_with(&root) {
                return true;
            }
        }
    }
    false
}

/// Walk up from `current_dir()` looking for the Altevra workspace root.
/// Returns the deepest matching Cargo.toml directory, or None if cwd is not
/// inside Altevra.
fn detect_altevra_workspace_from_cwd() -> Option<PathBuf> {
    let cwd = std::env::current_dir().ok()?;
    find_altevra_workspace_from(&cwd)
}

/// Walk up from `start` looking for a `Cargo.toml` that identifies as the
/// Altevra workspace (real package name match — NOT a raw substring scan).
/// Returns the directory containing that Cargo.toml.
fn find_altevra_workspace_from(start: &Path) -> Option<PathBuf> {
    let mut probe = start;
    loop {
        let cargo = probe.join("Cargo.toml");
        if cargo.exists() {
            if let Ok(text) = fs::read_to_string(&cargo) {
                if cargo_toml_is_altevra_workspace(&text) {
                    return Some(probe.to_path_buf());
                }
            }
        }
        match probe.parent() {
            Some(p) if p != probe => probe = p,
            _ => return None,
        }
    }
}

/// Decide whether a `Cargo.toml`'s content identifies it as an Altevra
/// workspace/crate. Uses a real TOML parse — a downstream Cargo.toml that
/// merely lists `altevra = "1.0"` as a dependency must NOT trigger self-skip.
///
/// Match criteria (any one is sufficient):
/// 1. `[package].name` equals `altevra` or starts with `altevra-`.
/// 2. `[workspace].members` contains any entry whose path segment starts
///    with `altevra-` or equals `altevra`/`crates/altevra` (covers the
///    workspace-root case where there is no `[package]`).
fn cargo_toml_is_altevra_workspace(text: &str) -> bool {
    let Ok(value) = toml::from_str::<toml::Value>(text) else {
        return false;
    };

    if let Some(name) = value
        .get("package")
        .and_then(|p| p.get("name"))
        .and_then(toml::Value::as_str)
    {
        if name == "altevra" || name.starts_with("altevra-") {
            return true;
        }
    }

    if let Some(members) = value
        .get("workspace")
        .and_then(|w| w.get("members"))
        .and_then(toml::Value::as_array)
    {
        for m in members {
            if let Some(s) = m.as_str() {
                let last = s.rsplit('/').next().unwrap_or(s);
                if last == "altevra" || last.starts_with("altevra-") {
                    return true;
                }
            }
        }
    }

    false
}

/// Append a JSON-ish line to `~/.altevra/install-hooks-decisions.log` recording
/// the global self-skip outcome. We use the same log file that smart-scope
/// writes to so a single forensic record covers every refusal.
fn log_self_skip_decision(home: &Path, repo_root: &Path, cwd: Option<&Path>, bypassed: bool) {
    let log_dir = home.join(".altevra");
    if let Err(_e) = fs::create_dir_all(&log_dir) {
        return;
    }
    let ts = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let action = if bypassed { "ALLOW-BYPASS" } else { "DENY" };
    let line = format!(
        "{ts}\tSELF-SKIP-GLOBAL\trepo={}\tcwd={}\taction={action}\tenv={SELF_SKIP_BYPASS_ENV}={}\n",
        repo_root.display(),
        cwd.map(|p| p.display().to_string()).unwrap_or_default(),
        if bypassed { "1" } else { "unset" }
    );
    let log_path = log_dir.join("install-hooks-decisions.log");
    let mut prior = fs::read_to_string(&log_path).unwrap_or_default();
    if !prior.is_empty() && !prior.ends_with('\n') {
        prior.push('\n');
    }
    prior.push_str(&line);
    let _ = fs::write(&log_path, prior);
}

// ───────────────────────────────────────────────────────────────────────────
// Smart auto-scope detection
// ───────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone)]
pub struct ScopeDecision {
    pub path: PathBuf,
    pub score: u8,
    pub action: String,
}

/// Walk projects + projects.yaml and decide per repo whether to also patch a
/// project-local `.claude/settings.json`. Decisions are logged to
/// `~/.altevra/install-hooks-decisions.log`. Score:
///   +1 has AGENTS.md or CLAUDE.md
///   +1 already has `.claude/settings.json` with non-altevra hooks
///   +1 listed in projects.yaml with a default_agent
///   +1 P0 or P1 priority in projects.yaml
/// Threshold: score >= 3 → patch.
pub fn smart_scope_apply(home: &Path, projects_root: &Path) -> Result<Vec<ScopeDecision>> {
    let log_dir = home.join(".altevra");
    fs::create_dir_all(&log_dir)?;
    let log_path = log_dir.join("install-hooks-decisions.log");

    let yaml_meta = load_projects_yaml(&home.join(".imperium/identity/projects.yaml"));
    let repos = walk_for_git_repos(projects_root);
    let mut decisions = Vec::new();
    let mut log_lines = Vec::new();
    let ts = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    for repo in repos {
        if repo.join(".altevra-skip").exists() {
            log_lines.push(format!(
                "{ts}\t{}\tSKIP\treason=altevra-skip-marker",
                repo.display()
            ));
            continue;
        }
        if is_altevra_repo_target(&repo) || repo_is_altevra(&repo) {
            log_lines.push(format!(
                "{ts}\t{}\tSKIP\treason=altevra-self",
                repo.display()
            ));
            continue;
        }
        let score = score_repo(&repo, &yaml_meta);
        let action = if score >= 3 {
            match write_project_claude_settings(&repo) {
                Ok(b) => {
                    if b {
                        "WROTE-PROJECT-CONFIG".to_string()
                    } else {
                        "SKIP-ALREADY-MANAGED".to_string()
                    }
                }
                Err(e) => format!("ERROR:{e}"),
            }
        } else {
            "SKIP-LOW-SCORE".to_string()
        };
        log_lines.push(format!(
            "{ts}\t{}\tscore={score}\taction={action}",
            repo.display()
        ));
        decisions.push(ScopeDecision {
            path: repo,
            score,
            action,
        });
    }

    // Append decisions log (never truncate — this is forensic history).
    let mut prior = fs::read_to_string(&log_path).unwrap_or_default();
    if !prior.is_empty() && !prior.ends_with('\n') {
        prior.push('\n');
    }
    prior.push_str(&log_lines.join("\n"));
    prior.push('\n');
    fs::write(&log_path, prior)?;

    Ok(decisions)
}

fn repo_is_altevra(repo: &Path) -> bool {
    let cargo = repo.join("Cargo.toml");
    if !cargo.exists() {
        return false;
    }
    fs::read_to_string(&cargo)
        .map(|t| cargo_toml_is_altevra_workspace(&t))
        .unwrap_or(false)
}

/// Walk `root` shallowly looking for git repos (1-2 levels deep — Pavle's
/// projects are categorized like `ai-tooling/altevra`, `biznis/revesta`).
fn walk_for_git_repos(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(top) = fs::read_dir(root) else {
        return out;
    };
    for entry in top.flatten() {
        let p = entry.path();
        if !p.is_dir() {
            continue;
        }
        if p.join(".git").exists() {
            out.push(p);
            continue;
        }
        if let Ok(inner) = fs::read_dir(&p) {
            for inner_entry in inner.flatten() {
                let q = inner_entry.path();
                if q.is_dir() && q.join(".git").exists() {
                    out.push(q);
                }
            }
        }
    }
    out
}

/// Minimal extract from projects.yaml: per-path → (default_agent_known, priority).
#[derive(Default)]
struct ProjectsMeta {
    by_path: std::collections::HashMap<PathBuf, (bool, String)>,
    paths: BTreeSet<PathBuf>,
}

fn load_projects_yaml(path: &Path) -> ProjectsMeta {
    let mut meta = ProjectsMeta::default();
    let Ok(text) = fs::read_to_string(path) else {
        return meta;
    };
    let Ok(root) = serde_yaml::from_str::<serde_yaml::Value>(&text) else {
        return meta;
    };
    let Some(projects) = root.get("projects").and_then(serde_yaml::Value::as_sequence) else {
        return meta;
    };
    for p in projects {
        let path_str = p.get("path").and_then(serde_yaml::Value::as_str);
        let agent = p.get("default_agent").and_then(serde_yaml::Value::as_str);
        let priority = p
            .get("priority")
            .and_then(serde_yaml::Value::as_str)
            .unwrap_or("")
            .to_string();
        if let Some(s) = path_str {
            let pb = PathBuf::from(s);
            meta.by_path.insert(pb.clone(), (agent.is_some(), priority));
            meta.paths.insert(pb);
        }
    }
    meta
}

fn score_repo(repo: &Path, yaml: &ProjectsMeta) -> u8 {
    let mut score = 0u8;
    if repo.join("AGENTS.md").exists() || repo.join("CLAUDE.md").exists() {
        score += 1;
    }
    let claude_settings = repo.join(".claude/settings.json");
    if claude_settings.exists() {
        if let Ok(text) = fs::read_to_string(&claude_settings) {
            if !text.contains(MANAGED_MARKER) && text.contains("\"hooks\"") {
                score += 1;
            }
        }
    }
    if let Some((agent_set, priority)) = yaml.by_path.get(repo) {
        if *agent_set {
            score += 1;
        }
        if priority == "P0" || priority == "P1" {
            score += 1;
        }
    }
    score
}

/// Write project-local `.claude/settings.json` with the same hook matrix. Same
/// idempotency rules apply. Returns Ok(true) if something was added.
fn write_project_claude_settings(repo: &Path) -> Result<bool> {
    let config = repo.join(".claude/settings.json");
    if !dir_writable(&config) {
        return Ok(false);
    }
    let outcome = patch_claude_style(config, "claude-code", false, false)?;
    Ok(!outcome.added_events.is_empty())
}

fn dir_writable(file: &Path) -> bool {
    let Some(dir) = file.parent() else {
        return false;
    };
    fs::create_dir_all(dir).is_ok()
}

