use clap::Args;
use std::path::PathBuf;

#[derive(Args)]
pub struct InitArgs {
    /// Path to initialize (defaults to current directory)
    #[arg(long, short, default_value = ".")]
    pub path: PathBuf,

    /// Force reinitialize even if already initialized
    #[arg(long)]
    pub force: bool,

    /// Preview initialization without writing files
    #[arg(long)]
    pub dry_run: bool,

    /// Output as JSON
    #[arg(long)]
    pub json: bool,
}

#[derive(serde::Serialize)]
struct InitResult {
    initialized: bool,
    dry_run: bool,
    path: String,
    created_dirs: Vec<String>,
    created_files: Vec<String>,
    already_existed: Vec<String>,
}

pub async fn run(args: InitArgs) -> anyhow::Result<()> {
    let root = args
        .path
        .canonicalize()
        .unwrap_or_else(|_| args.path.clone());
    let altevra_dir = root.join(".altevra");

    let mut created_dirs = vec![];
    let mut created_files = vec![];
    let mut already_existed = vec![];

    // Create directory structure
    let dirs = [
        altevra_dir.join("vault"),
        altevra_dir.join("events"),
        root.join("06-skills"),
        root.join("07-capabilities"),
        root.join("15-generated/setup-packs"),
    ];

    for dir in &dirs {
        if dir.exists() {
            already_existed.push(dir.display().to_string());
        } else {
            if !args.dry_run {
                std::fs::create_dir_all(dir)?;
            }
            created_dirs.push(dir.display().to_string());
        }
    }

    // Create default config
    let config_path = altevra_dir.join("config.toml");
    if !config_path.exists() || args.force {
        if !args.dry_run {
            let config = include_default_config();
            std::fs::write(&config_path, config)?;
        }
        created_files.push(config_path.display().to_string());
    } else {
        already_existed.push(config_path.display().to_string());
    }

    // Create default hooks.yaml
    let hooks_path = root.join("07-capabilities/hooks.yaml");
    if !hooks_path.exists() || args.force {
        if !args.dry_run {
            std::fs::write(&hooks_path, default_hooks_yaml())?;
        }
        created_files.push(hooks_path.display().to_string());
    } else {
        already_existed.push(hooks_path.display().to_string());
    }

    // Create default agent-tools.yaml
    let tools_path = root.join("07-capabilities/agent-tools.yaml");
    if !tools_path.exists() || args.force {
        if !args.dry_run {
            std::fs::write(&tools_path, default_agent_tools_yaml())?;
        }
        created_files.push(tools_path.display().to_string());
    } else {
        already_existed.push(tools_path.display().to_string());
    }

    let result = InitResult {
        initialized: !args.dry_run,
        dry_run: args.dry_run,
        path: root.display().to_string(),
        created_dirs,
        created_files,
        already_existed,
    };

    if args.json {
        println!("{}", serde_json::to_string_pretty(&result)?);
    } else {
        if args.dry_run {
            println!("Altevra init dry-run at: {}", root.display());
        } else {
            println!("Altevra initialized at: {}", root.display());
        }
        if !result.created_dirs.is_empty() {
            let label = if args.dry_run {
                "Directories to create"
            } else {
                "Created directories"
            };
            println!("\n{label}:");
            for d in &result.created_dirs {
                println!("  + {d}");
            }
        }
        if !result.created_files.is_empty() {
            let label = if args.dry_run {
                "Files to create"
            } else {
                "Created files"
            };
            println!("\n{label}:");
            for f in &result.created_files {
                println!("  + {f}");
            }
        }
        if !result.already_existed.is_empty() {
            println!("\nAlready existed (skipped):");
            for e in &result.already_existed {
                println!("  ~ {e}");
            }
        }
        if args.dry_run {
            println!("\nDry-run only: no files were written.");
        }
        println!("\nNext: altevra connect --tool claude-code --project <name> --dry-run");
    }

    Ok(())
}

fn include_default_config() -> String {
    r#"# Altevra Configuration
# Generated by: altevra init

[database]
# Set ALTEVRA_DATABASE_URL or configure here
url = "postgres://localhost/altevra"
max_connections = 10

[vault]
# Path to the Altevra vault directory
# Defaults to current directory (.)
path = "."

[altevra]
version = "0.1.0"
"#
    .to_string()
}

