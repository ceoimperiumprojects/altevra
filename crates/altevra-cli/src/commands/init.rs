#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    #[tokio::test]
    async fn test_init_creates_structure() {
        let tmp = TempDir::new().unwrap();
        let args = InitArgs {
            path: tmp.path().to_path_buf(),
            force: false,
            dry_run: false,
            json: false,
        };
        run(args).await.unwrap();

        assert!(tmp.path().join(".altevra").exists());
        assert!(tmp.path().join(".altevra/vault").exists());
        assert!(tmp.path().join("06-skills").exists());
        assert!(tmp.path().join("07-capabilities").exists());
        assert!(tmp.path().join("07-capabilities/hooks.yaml").exists());
        assert!(tmp.path().join("07-capabilities/agent-tools.yaml").exists());
    }

    #[tokio::test]
    async fn test_init_json_output() {
        let tmp = TempDir::new().unwrap();
        let args = InitArgs {
            path: tmp.path().to_path_buf(),
            force: false,
            dry_run: false,
            json: true,
        };
        // Should not panic or error
        run(args).await.unwrap();
    }

    #[tokio::test]
    async fn test_init_idempotent() {
        let tmp = TempDir::new().unwrap();
        for _ in 0..2 {
            let args = InitArgs {
                path: tmp.path().to_path_buf(),
                force: false,
                dry_run: false,
                json: false,
            };
            run(args).await.unwrap();
        }
        // Second run should not fail
        assert!(tmp.path().join(".altevra").exists());
    }

    #[tokio::test]
    async fn test_init_dry_run_has_no_side_effects() {
        let tmp = TempDir::new().unwrap();
        let args = InitArgs {
            path: tmp.path().to_path_buf(),
            force: false,
            dry_run: true,
            json: false,
        };

        run(args).await.unwrap();

        assert!(!tmp.path().join(".altevra").exists());
        assert!(!tmp.path().join("06-skills").exists());
        assert!(!tmp.path().join("07-capabilities").exists());
        assert!(!tmp.path().join("15-generated").exists());
    }
}
